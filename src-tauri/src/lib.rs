//! Jifar desktop shell: window, IPC and app state. Domain logic lives in the
//! `jifar-*` crates.

mod commands;
mod error;

use std::path::Path;

use anyhow::Context;
use jifar_core::paths::AppPaths;
use specta_typescript::Typescript;
use tauri_specta::{Builder, collect_commands};

pub use error::{AppError, ErrorCode};

pub struct AppState {
    pub paths: AppPaths,
}

/// Generated TS bindings, checked into the repo and verified in CI.
pub const BINDINGS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings.ts");

fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new().commands(collect_commands![commands::ping])
}

pub fn export_bindings(path: &Path) -> anyhow::Result<()> {
    specta_builder()
        .export(
            Typescript::default()
                .header("// @ts-nocheck\n// Generated by tauri-specta. Do not edit.\n"),
            path,
        )
        .context("exporting TypeScript bindings")
}

pub fn run() -> anyhow::Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "info,jifar=debug".into()),
        )
        .init();

    let paths = AppPaths::from_env().context("resolving data directories")?;
    paths.ensure().context("creating data directories")?;
    tracing::info!(data_dir = %paths.data_dir.display(), "starting Jifar");

    #[cfg(debug_assertions)]
    export_bindings(Path::new(BINDINGS_PATH))?;

    let builder = specta_builder();
    tauri::Builder::default()
        .manage(AppState { paths })
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            Ok(())
        })
        .run(tauri::generate_context!())
        .context("running Tauri application")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Regenerates `src/bindings.ts`. CI runs this and fails on a git diff,
    /// so the IPC contract can't drift from the Rust side.
    #[test]
    fn export_typescript_bindings() {
        export_bindings(Path::new(BINDINGS_PATH)).unwrap();
    }
}
